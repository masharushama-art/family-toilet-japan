// 手書きTipsが無い都市向け：実際の統計値(getCityStats)から都市固有の文章を組み立てる
export function buildDataDrivenTipsJa(cityName: string, stats: ReturnType<typeof getCityStats>): string[] {
  const pct = (n: number) => Math.round((n / Math.max(stats.total, 1)) * 100);
  return [
    `${cityName}には現在${stats.total.toLocaleString()}件のトイレを収録しており、うち${stats.withChangingTable.toLocaleString()}件がおむつ交換台付きです。地図では🍼アイコンで確認できます。`,
    `${cityName}のトイレのうち${pct(stats.wheelchair)}%（${stats.total.toLocaleString()}件中${stats.wheelchair.toLocaleString()}件）が車いす対応です。`,
    stats.free === stats.total
      ? `${cityName}で収録している${stats.total.toLocaleString()}件のトイレはすべて無料で利用できます。`
      : `${cityName}のトイレのうち${stats.free.toLocaleString()}件が無料で利用できます。観光地の一部では有料の場合があります。`,
    "コンビニ（セブンイレブン・ローソン・ファミリーマート）は24時間営業で、ほとんどの店舗でトイレを利用できます。",
  ];
}
